/**
 * Access-road traffic: a SIMPLIFIED SENSITIVITY TEST, not a network simulation.
 *
 * What it is. One access road, named by the user or taken from a confirmed access relationship,
 * carrying an assumed baseline volume. The scenario's additional occupied spaces generate
 * additional peak-hour arrivals and departures. Those are added to the baseline and compared with
 * an assumed capacity, and a time-step model estimates how a queue would build and clear.
 *
 * What it is NOT, stated because the output invites the opposite reading:
 *
 *   It is not route assignment. The county centreline file carries no topology, turn
 *   restrictions or connectivity, so there is no network to route over. Trips are assigned to ONE
 *   road the user nominates — that is the whole assignment step, and the result is labelled as a
 *   single-approach sensitivity analysis rather than a port-wide traffic model.
 *
 *   V/C is not congestion. A volume-over-capacity ratio of 1.1 says the assumed demand exceeds
 *   the assumed capacity of one approach. It is not a measured speed, a delay, or a level of
 *   service, and nothing here converts it into one.
 *
 *   No lane count or capacity is published for these segments, so both are assumptions.
 *
 * The queue model steps through the analysis period in five-minute slices. Vehicles are
 * conserved: what arrives either departs the queue or stays in it, the queue never goes negative,
 * and a test asserts both.
 */

const finite = value => {
  if (value === null || value === undefined || value === '') return null;
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
};

export const STEP_MINUTES = 5;

/** This result describes one nominated approach, and says so wherever it is shown. */
export const TRAFFIC_SCOPE =
  'Single access-road sensitivity test. Trips are assigned to one nominated approach; the road '
  + 'file has no topology, so no routing or network effect is modelled.';

/**
 * Additional peak-hour vehicles generated by a scenario.
 *
 * Arrivals come from the OCCUPIED additional spaces, not from the built ones: an empty deck
 * generates no trips, and multiplying capacity by an arrival share would overstate every
 * alternative in proportion to how much spare room it has.
 */
export function generatedTrips({ additionalSpaces, utilisationPct, peakArrivalSharePct, peakDepartureSharePct, vehiclesPerSpace }) {
  const spaces = finite(additionalSpaces);
  const utilisation = finite(utilisationPct);
  const arrivalShare = finite(peakArrivalSharePct);
  const departureShare = finite(peakDepartureSharePct);
  const perSpace = finite(vehiclesPerSpace);
  if ([spaces, utilisation, arrivalShare, departureShare, perSpace].some(v => v === null)) {
    return { occupied: null, arrivals: null, departures: null, total: null };
  }
  const occupied = spaces * (utilisation / 100) * perSpace;
  const arrivals = Math.round(occupied * (arrivalShare / 100));
  const departures = Math.round(occupied * (departureShare / 100));
  return { occupied: Math.round(occupied), arrivals, departures, total: arrivals + departures };
}

/**
 * Assumed capacity of the nominated approach, with construction's share removed when the scenario
 * is being modelled during works.
 */
export function roadCapacity({ roadCapacityPerLane, accessLanes, constructionLaneClosurePct = 0, duringConstruction = false }) {
  const perLane = finite(roadCapacityPerLane);
  const lanes = finite(accessLanes);
  if (perLane === null || lanes === null || lanes <= 0) return { capacity: null, lost: null };
  const full = perLane * lanes;
  const lostPct = duringConstruction ? (finite(constructionLaneClosurePct) ?? 0) : 0;
  return { capacity: Math.round(full * (1 - lostPct / 100)), fullCapacity: full, lostPct };
}

/**
 * A deterministic deterministic-service queue over the analysis period.
 *
 * Demand arrives evenly across the period; the approach serves at its capacity rate. Each slice:
 * the queue takes everything that arrives, releases what can be served, and carries the rest.
 *
 * @returns {{steps, peakQueue, endQueue, totalArrived, totalServed, clearanceMinutes}}
 */
export function queueModel({ demandPerHour, capacityPerHour, analysisMinutes, stepMinutes = STEP_MINUTES }) {
  const demand = finite(demandPerHour);
  const capacity = finite(capacityPerHour);
  const minutes = finite(analysisMinutes);
  if (demand === null || capacity === null || minutes === null || capacity <= 0 || minutes <= 0) {
    return { steps: [], peakQueue: null, endQueue: null, totalArrived: null, totalServed: null, clearanceMinutes: null };
  }
  const slices = Math.max(1, Math.round(minutes / stepMinutes));
  const arrivalsPerStep = (demand * stepMinutes) / 60;
  const servicePerStep = (capacity * stepMinutes) / 60;

  const steps = [];
  let queue = 0, totalArrived = 0, totalServed = 0;
  for (let i = 0; i < slices; i += 1) {
    queue += arrivalsPerStep;
    totalArrived += arrivalsPerStep;
    const served = Math.min(queue, servicePerStep);   // never serves more than is present
    queue -= served;                                   // so the queue cannot go negative
    totalServed += served;
    steps.push({ minute: (i + 1) * stepMinutes, arrived: arrivalsPerStep, served, queue });
  }

  // How long the residual queue takes to clear once the peak demand stops, at the same service
  // rate. Null when demand meets or exceeds capacity, because then it does not clear.
  const clearanceMinutes = queue > 0
    ? (capacity > demand ? (queue / capacity) * 60 : null)
    : 0;

  return {
    steps,
    peakQueue: steps.reduce((most, step) => Math.max(most, step.queue), 0),
    endQueue: queue,
    totalArrived,
    totalServed,
    clearanceMinutes,
    /** Conservation, carried in the result so a caller can assert it rather than trust it. */
    conserved: Math.abs((totalArrived - totalServed) - queue) < 1e-6,
  };
}

/**
 * The traffic result for one scenario on one nominated approach.
 *
 * @param {object} input
 * @param {object} input.trips       from generatedTrips
 * @param {number} input.baselineRoadVolume
 * @param {object} input.capacity    from roadCapacity
 * @param {number} input.analysisMinutes
 * @param {{objectId: number, name: string}|null} input.road  the nominated approach
 */
export function trafficResult({ trips, baselineRoadVolume, capacity, analysisMinutes, road = null }) {
  const baseline = finite(baselineRoadVolume);
  const added = trips?.total ?? null;
  const assumedCapacity = capacity?.capacity ?? null;

  if (baseline === null || added === null || assumedCapacity === null) {
    return {
      road, scope: TRAFFIC_SCOPE,
      baselineVolume: baseline, addedVehicles: added, totalVolume: null,
      assumedCapacity, vcRatio: null, exceedsCapacity: null, queue: null,
      reason: 'Not calculated — a traffic assumption or the access road is missing.',
    };
  }

  const totalVolume = baseline + added;
  const queue = queueModel({ demandPerHour: totalVolume, capacityPerHour: assumedCapacity, analysisMinutes });

  return {
    road,
    scope: TRAFFIC_SCOPE,
    baselineVolume: baseline,
    addedVehicles: added,
    addedArrivals: trips.arrivals,
    addedDepartures: trips.departures,
    totalVolume,
    assumedCapacity,
    /** Demand over assumed capacity on ONE approach. Not a measure of congestion or delay. */
    vcRatio: assumedCapacity > 0 ? totalVolume / assumedCapacity : null,
    exceedsCapacity: totalVolume > assumedCapacity,
    capacityExceedanceVeh: Math.max(0, totalVolume - assumedCapacity),
    queue,
    reason: null,
  };
}
